"""
Render docs/cofog-to-services.md from config/taxonomy/services.csv and cofog.csv, for review.

Every COFOG concept is shown with the service it rolls up to (longest prefix wins).

Usage:
  python src/docs/render_service_map.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from clean.common import read_csv  # noqa: E402
from paths import REPO, TAXONOMY, rel  # noqa: E402
from services import service_for  # noqa: E402


def main() -> int:
    services = {s["service_id"]: s for s in read_csv(TAXONOMY / "services.csv")}
    lines = ["# COFOG to service map", "",
             "Generated by `src/docs/render_service_map.py` from `config/taxonomy/services.csv`; edit the CSV, not this file.",
             "Each COFOG concept published by Statistics Canada (CCOFOG) rolls up to one service. Within a service, the more specific",
             "prefix wins (e.g. `10.2` Seniors' Benefits before `10` Social Assistance).", "",
             "| COFOG | Name | Level | Service |", "|---|---|---|---|"]
    for c in read_csv(TAXONOMY / "cofog.csv"):
        sid = service_for(c["concept_id"])
        indent = "" if c["level"] == "division" else "&nbsp;&nbsp;&nbsp;"
        name = f"**{c['name']}**" if c["level"] == "division" else c["name"]
        lines.append(f"| {c['concept_id']} | {indent}{name} | {c['level']} | {services[sid]['name']} |")
    lines += ["", "Special concepts:", "",
              "| Concept | Service |", "|---|---|",
              f"| `_unallocated` (line spans several functions) | {services['unidentified']['name']} |",
              f"| Provincial override rows in `config/output/category-overrides.csv` | {services['municipal_transfers']['name']} |"]
    dest = REPO / "docs" / "cofog-to-services.md"
    dest.write_text("\n".join(lines) + "\n")
    print(f"OK   {rel(dest)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
